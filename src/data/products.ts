export function getProduct(slug: string) {
  return PRODUCTS.find((p) => p.slug === slug);
}
export function relatedProducts(slug: string, n = 4) {
  const cur = getProduct(slug);
  if (!cur) return PRODUCTS.slice(0, n);
  const sameCat = PRODUCTS.filter((p) => p.slug !== slug && p.category === cur.category);
  const rest = PRODUCTS.filter((p) => p.slug !== slug && p.category !== cur.category);
  return [...sameCat, ...rest].slice(0, n);
}
export function formatPrice(n: number) {
  return new Intl.NumberFormat("en-US", { style: "currency", currency: "USD", maximumFractionDigits: n % 1 === 0 ? 0 : 2 }).format(n);
}
